import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFile } from "node:fs/promises";
import { buildCss } from "./scripts/build-css.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the GitHub repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const watch = process.argv[2] === "watch";
const themeCssModule = "virtual:brewvault-theme-css";

const themeCssModulePlugin = {
  name: "brewvault-theme-css-module",
  setup(build) {
    build.onResolve({ filter: /^virtual:brewvault-theme-css$/ }, () => ({
      path: themeCssModule,
      namespace: "brewvault-theme-css",
    }));
    build.onLoad(
      { filter: /.*/, namespace: "brewvault-theme-css" },
      async () => ({
        contents: `export const BUNDLED_THEME_CSS = ${JSON.stringify(
          await readFile("styles.css", "utf8")
        )};`,
        loader: "js",
      })
    );
  },
};

// CSS must exist before the virtual module snapshots it into the JS bundle.
await buildCss(prod);

const jsContext = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [themeCssModulePlugin],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
	...builtinModules,
	...builtinModules.map((moduleName) => `node:${moduleName}`),
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (watch) {
  const cssContext = await esbuild.context({
    entryPoints: ["styles/index.css"],
    bundle: true,
    outfile: "styles.css",
    logLevel: "info",
    plugins: [
      {
        name: "rebuild-theme-css-module",
        setup(build) {
          build.onEnd(async (result) => {
            if (result.errors.length > 0) return;
            await buildCss(false);
            await jsContext.rebuild();
          });
        },
      },
    ],
  });
  await cssContext.watch();
  await jsContext.watch();
} else {
  await jsContext.rebuild();
  process.exit(0);
}
